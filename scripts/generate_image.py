#!/usr/bin/env python3
"""generate_image.py — 可插拔图片生成器。

Usage:
    python generate_image.py --prompt "<prompt>" --out <output.png>

实现策略（由 runtime 选择）：
1. 检测环境变量 CLAUDE_IMAGE_GEN=1 → 标记将由 Claude 主代理生成；
2. 检测 huashu-gpt-image skill 是否可用；
3. 检测本地 SDXL FastAPI（默认 http://127.0.0.1:7860）；
4. 全部不可用 → 退出码 3，stderr 报告缺失能力。

本脚本仅作为可插拔接口存在；当 CLAUDE_IMAGE_GEN=1 时，
实际生成由 Claude 会话内的图片大模型完成，本脚本只创建占位 .prompt.txt
供主代理读取并生成。
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path


def detect_backend() -> str:
    if os.environ.get("MINIMAX_IMAGE_GEN") == "1":
        return "minimax-m3"
    try:
        import requests  # type: ignore

        r = requests.get("http://127.0.0.1:7860/sdapi/v1/sd-models", timeout=1)
        if r.ok:
            return "sdxl-local"
    except Exception:
        pass
    return "unavailable"


STYLE_SUFFIX = """

【视觉规范（自动注入，详见 references/image-style.md）】
- 文字容器宽度 ≥ 文字宽度 × 1.2，长文本自动换行，禁止单行溢出
- 容器高度自适应内容，禁止固定高度截断
- 文字与容器边距 ≥ 1.5 倍行距
- 深色背景必须配浅色文字（白色 #FFFFFF 或 浅灰 #F0F0F0）
- 浅色背景必须配深色文字（深蓝 #003070 或 深灰 #222）
- 文字与背景对比度 ≥ 4.5:1（WCAG AA 标准）
- 字号：标题 ≥ 36px，正文 ≥ 24px
- 禁止"深色文字 + 深色背景"或"浅色文字 + 浅色背景"组合
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--prompt", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--negative", default="")
    parser.add_argument(
        "--no-style-suffix",
        action="store_true",
        help="禁止自动注入视觉规范段（默认注入）",
    )
    args = parser.parse_args()

    backend = detect_backend()
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)

    full_prompt = args.prompt if args.no_style_suffix else args.prompt + STYLE_SUFFIX

    if backend == "minimax-m3":
        # Claude/MiniMax-M3 会话内由主代理读取 .prompt.txt 并调用 MiniMax-M3 图片大模型
        prompt_file = out.with_suffix(".prompt.txt")
        prompt_file.write_text(
            f"PROMPT:\n{full_prompt}\n\nNEGATIVE:\n{args.negative}\n\nBACKEND: MiniMax-M3\n",
            encoding="utf-8",
        )
        print(
            f"MINIMAX_M3_BACKEND: wrote prompt to {prompt_file}; "
            "image will be generated by MiniMax-M3 via Claude agent"
        )
        return 0

    if backend == "sdxl-local":
        try:
            import requests  # type: ignore

            payload = {
                "prompt": full_prompt,
                "negative_prompt": args.negative,
                "steps": 25,
                "width": 1024,
                "height": 768,
            }
            r = requests.post("http://127.0.0.1:7860/sdapi/v1/txt2img", json=payload, timeout=600)
            r.raise_for_status()
            import base64

            img_b64 = r.json()["images"][0]
            out.write_bytes(base64.b64decode(img_b64))
            print(f"SDXL_OK: {out} ({out.stat().st_size} bytes)")
            return 0
        except Exception as exc:
            print(f"ERROR: SDXL generation failed: {exc}", file=sys.stderr)
            return 4

    print("ERROR: no image generation backend available", file=sys.stderr)
    return 3


if __name__ == "__main__":
    sys.exit(main())